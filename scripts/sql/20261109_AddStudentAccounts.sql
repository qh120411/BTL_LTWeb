-- SQL Server UNIQUE constraints allow only one NULL. These optional one-to-one
-- links must instead be unique only for non-NULL IDs, as EF Core expects.
DECLARE @constraint sysname;
DECLARE @command nvarchar(max);
SELECT @constraint = kc.name
FROM sys.key_constraints kc
JOIN sys.index_columns ic ON ic.object_id=kc.parent_object_id AND ic.index_id=kc.unique_index_id
JOIN sys.columns c ON c.object_id=ic.object_id AND c.column_id=ic.column_id
WHERE kc.parent_object_id=OBJECT_ID(N'dbo.TaiKhoan') AND kc.type='UQ'
  AND c.name=N'MaNhanVien'
  AND (SELECT COUNT(*) FROM sys.index_columns x WHERE x.object_id=kc.parent_object_id AND x.index_id=kc.unique_index_id AND x.key_ordinal>0)=1;
IF @constraint IS NOT NULL
BEGIN
    SET @command = N'ALTER TABLE dbo.TaiKhoan DROP CONSTRAINT ' + QUOTENAME(@constraint);
    EXEC sys.sp_executesql @command;
END;
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.TaiKhoan') AND name=N'UX_TaiKhoan_MaNhanVien_NotNull')
    CREATE UNIQUE INDEX UX_TaiKhoan_MaNhanVien_NotNull ON dbo.TaiKhoan(MaNhanVien) WHERE MaNhanVien IS NOT NULL;

SET @constraint = NULL;
SELECT @constraint = kc.name
FROM sys.key_constraints kc
JOIN sys.index_columns ic ON ic.object_id=kc.parent_object_id AND ic.index_id=kc.unique_index_id
JOIN sys.columns c ON c.object_id=ic.object_id AND c.column_id=ic.column_id
WHERE kc.parent_object_id=OBJECT_ID(N'dbo.TaiKhoan') AND kc.type='UQ'
  AND c.name=N'MaBanDoc'
  AND (SELECT COUNT(*) FROM sys.index_columns x WHERE x.object_id=kc.parent_object_id AND x.index_id=kc.unique_index_id AND x.key_ordinal>0)=1;
IF @constraint IS NOT NULL
BEGIN
    SET @command = N'ALTER TABLE dbo.TaiKhoan DROP CONSTRAINT ' + QUOTENAME(@constraint);
    EXEC sys.sp_executesql @command;
END;
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.TaiKhoan') AND name=N'UX_TaiKhoan_MaBanDoc_NotNull')
    CREATE UNIQUE INDEX UX_TaiKhoan_MaBanDoc_NotNull ON dbo.TaiKhoan(MaBanDoc) WHERE MaBanDoc IS NOT NULL;

